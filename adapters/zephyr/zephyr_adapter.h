#ifndef WEBSERVER_ADAPTERS_ZEPHYR_ZEPHYR_ADAPTER_
#define WEBSERVER_ADAPTERS_ZEPHYR_ZEPHYR_ADAPTER_

#include <zephyr/net/http/server.h>
#include <zephyr/net/http/service.h>
#include <zephyr/sys/util.h>

#include <array>
#include <cstddef>
#include <cstdint>

#include "webserver/http_server.h"
#include "webserver/http_types.h"

// Connects HttpServer to Zephyr's HTTP server (CONFIG_HTTP_SERVER).
//
// Zephyr gives a dynamic resource to one client at a time and answers 409
// to the others, so a single catch-all resource would fail the browser's
// parallel requests. Instead the embedded files become Zephyr static
// resources (WEBSERVER_ZEPHYR_STATIC_RESOURCES) and every API path gets its
// own dynamic resource (WEBSERVER_ZEPHYR_API_RESOURCES); both are generated
// from the same lists as the other platforms use:
//
//   HTTP_SERVICE_DEFINE(web_service, nullptr, &port, 4, 4, nullptr,
//                       nullptr, nullptr);
//   webserver::zephyr::Adapter adapter{web.server()};
//   WEBSERVER_ZEPHYR_STATIC_RESOURCES(web_service)
//   WEBSERVER_ZEPHYR_API_RESOURCES(web_service, adapter)
//
// (the service needs `_detail` and `_res_fallback` NULL: unknown paths get
// Zephyr's 404).
//
// Needs CONFIG_HTTP_SERVER_CAPTURE_HEADERS (Authorization and Content-Type
// are captured; Zephyr fills client->content_type only for HTTP/2).
namespace webserver::zephyr {

class Adapter;

// State of one API resource. Zephyr serves all clients from one thread and
// a POST body may arrive in several callbacks, interleaved with other
// resources' callbacks, so each resource collects its own request.
struct Endpoint {
  Adapter& adapter;
  alignas(8) std::array<std::uint8_t, kMaxRequestBodySize> body{};
  std::size_t body_size = 0;
  bool too_large = false;
  bool started = false;
  // Captured headers. Longer values are not ones the API accepts, so they
  // are dropped (the router then answers 401 or 415).
  std::array<char, 64> authorization{};  // "Bearer " and a session token
  std::size_t authorization_size = 0;
  std::array<char, 48> content_type{};
  std::size_t content_type_size = 0;
};

class Adapter {
 public:
  explicit Adapter(const HttpServer& server) noexcept : server_(server) {}

  Adapter(const Adapter&) = delete;
  Adapter& operator=(const Adapter&) = delete;

  // http_resource_dynamic_cb_t; `user_data` is the resource's Endpoint.
  static int Callback(http_client_ctx* client,
                      enum http_transaction_status status,
                      const http_request_ctx* request_ctx,
                      http_response_ctx* response_ctx, void* user_data);

 private:
  int Handle(http_client_ctx* client, enum http_transaction_status status,
             const http_request_ctx* request_ctx,
             http_response_ctx* response_ctx, Endpoint& endpoint) noexcept;
  void Respond(http_response_ctx* response_ctx) noexcept;

  const HttpServer& server_;
  // One response at a time is enough: Zephyr sends it before the callback
  // of another client runs.
  HttpResponse response_;
  std::array<http_header, 4> headers_{};
};

// Methods the API resources accept; the router answers 405 for the others.
inline constexpr std::uint32_t kApiMethods =
    BIT(HTTP_GET) | BIT(HTTP_POST) | BIT(HTTP_PUT) | BIT(HTTP_DELETE);

}  // namespace webserver::zephyr

// Every file of WEBSERVER_WEB_RESOURCES (web_resources.h, generated by the
// UI build) as a static resource of `_service`. Use at namespace scope.
#define WEBSERVER_ZEPHYR_STATIC_RESOURCES(_service) \
  WEBSERVER_WEB_RESOURCES(WEBSERVER_ZEPHYR_INTERNAL_STATIC, _service)

// Every path of WEBSERVER_API_PATHS (web_application.h) as a dynamic
// resource of `_service` handled by `_adapter`. Use at namespace scope.
#define WEBSERVER_ZEPHYR_API_RESOURCES(_service, _adapter) \
  WEBSERVER_API_PATHS(WEBSERVER_ZEPHYR_INTERNAL_API, _service, _adapter)

#define WEBSERVER_ZEPHYR_INTERNAL_STATIC(_service, _n, _path, _type,       \
                                         _encoding, _cache, _data)         \
  static struct http_resource_detail_static                                \
      webserver_static_detail_##_n = {                                     \
          .common = {.bitmask_of_supported_http_methods = BIT(HTTP_GET),   \
                     .type = HTTP_RESOURCE_TYPE_STATIC,                    \
                     .content_encoding =                                   \
                         (_encoding)[0] != '\0' ? (_encoding) : nullptr,   \
                     .content_type = (_type)},                             \
          .static_data = (_data),                                          \
          .static_data_len = sizeof(_data),                                \
  };                                                                       \
  HTTP_RESOURCE_DEFINE(webserver_static_##_n, _service, _path,             \
                       &webserver_static_detail_##_n);

#define WEBSERVER_ZEPHYR_INTERNAL_API(_service, _adapter, _n, _path)         \
  static ::webserver::zephyr::Endpoint webserver_api_endpoint_##_n{          \
      _adapter};                                                             \
  static struct http_resource_detail_dynamic webserver_api_detail_##_n = {   \
      .common = {.bitmask_of_supported_http_methods =                        \
                     ::webserver::zephyr::kApiMethods,                       \
                 .type = HTTP_RESOURCE_TYPE_DYNAMIC,                         \
                 .content_type = "text/plain"},                              \
      .cb = &::webserver::zephyr::Adapter::Callback,                         \
      .user_data = &webserver_api_endpoint_##_n,                             \
  };                                                                         \
  HTTP_RESOURCE_DEFINE(webserver_api_##_n, _service, _path,                  \
                       &webserver_api_detail_##_n);

#endif  // WEBSERVER_ADAPTERS_ZEPHYR_ZEPHYR_ADAPTER_
